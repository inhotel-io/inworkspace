#!/usr/bin/env node
// Writes src/lib/trace-event-types.json: the events the tracing webhook subscribes to, from the
// server's own event table (crates/trc/src/event/enums_impl.rs).
//
// The server's webhooks ignore their level setting and send exactly the events they list, so the
// list is chosen here: every event at info level or above, as a log at level info would show, plus
// the debug-level events that make a delivery trace readable (the SMTP session's start and end,
// authentication results, the delivery steps). Trace-level events (raw protocol lines) are left out.
import { readFileSync, writeFileSync } from "node:fs";

const source = readFileSync(new URL("../../crates/trc/src/event/enums_impl.rs", import.meta.url), "utf8");

const levelStart = source.indexOf("pub fn level(&self) -> Level");
const levelEnd = source.indexOf("pub fn description(&self)", levelStart);
if (levelStart < 0 || levelEnd < 0) throw new Error("the event level table was not found");
const levels = new Map();
for (const [, group, variant, level] of source.slice(levelStart, levelEnd).matchAll(/EventType::(\w+)\(\s*\w+::(\w+)\s*\)\s*=>\s*\{?\s*Level::(\w+)/g)) {
  levels.set(`${group}::${variant}`, level);
}
const names = new Map();
for (const [, group, variant, name] of source.matchAll(/EventType::(\w+)\(\s*\w+::(\w+)\s*\)\s*=>\s*\{?\s*"([a-z0-9.-]+)"/g)) {
  if (!names.has(`${group}::${variant}`)) names.set(`${group}::${variant}`, name);
}
if (levels.size < 100 || names.size < 400) throw new Error(`the event tables look wrong (${levels.size} levels, ${names.size} names)`);

/** Debug-level groups whose events belong in a delivery trace, and the chatty ones left out of them. */
const DELIVERY_GROUPS = new Set(["smtp", "delivery", "auth", "spf", "dkim", "dmarc", "iprev", "arc", "sieve", "tls"]);
const LEFT_OUT = new Set(["smtp.noop", "smtp.rset", "smtp.quit", "smtp.help"]);
const ALSO = new Set(["spam.classify", "queue.blob-not-found"]);

const events = [];
for (const [key, name] of names) {
  // Events missing from the level table are at debug level.
  const level = levels.get(key) ?? "Debug";
  if (level === "Trace" || LEFT_OUT.has(name)) continue;
  const group = name.split(".")[0];
  if (level !== "Debug" || DELIVERY_GROUPS.has(group) || ALSO.has(name)) events.push(name);
}
events.sort();

const target = new URL("../src/lib/trace-event-types.json", import.meta.url);
writeFileSync(target, `${JSON.stringify({ about: "Generated by scripts/generate-trace-events.mjs; do not edit.", events }, null, 2)}\n`);
console.log(`${events.length} event types written to ${target.pathname}`);
